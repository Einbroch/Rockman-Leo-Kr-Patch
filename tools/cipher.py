def syllables():
    """암호에 쓰인 음절(자판에 꼭 넣을 것), 처음 나온 차례대로."""
    out = []
    for text in [SUBJECT] + list(PASSWORDS.values()):
        for c in text:
            if c not in out:
                out.append(c)
    return out


def check():
    """암호가 규칙(한글 음절만, 길이)을 지키는지. 어긋난 것 목록."""
    bad = []
    for n, text in PASSWORDS.items():
        if not re.fullmatch('[가-힣]+', text) or len(text) > BODY_MAX:
            bad.append((n, text))
    if len(SUBJECT) > SUBJECT_MAX:
        bad.append(('제목', SUBJECT))
    return bad


def write_tpl():
    """script/ko/0098.tpl 을 일본판 틀에서 만든다(제목 줄은 「암호」, 본문 줄은 한국어 암호)."""
    bad = check()
    if bad:
        raise SystemExit(f'암호가 규칙에 맞지 않습니다: {bad}')
    text = JA_TPL.read_text(encoding='utf-8')
    out, seen = [], set()
    for m in re.finditer(r'script (\d+) mmsf1 \{\n\t"([^"\n]*)"\n\tend\n\}\n', text):
        n, ja = int(m.group(1)), m.group(2)
        ko = SUBJECT if ja == 'あんごう' else PASSWORDS.get(n)
        if ko is None:
            raise SystemExit(f'블록 98 스크립트 {n}({ja!r})의 한국어 암호가 없습니다')
        out.append(f'script {n} mmsf1 {{\n\t"{ko}"\n\tend\n}}\n')
        seen.add(n)
    missing = set(PASSWORDS) - seen
    if missing:
        raise SystemExit(f'일본판 블록 98 에 없는 줄 번호: {sorted(missing)}')
    head = text[:text.index('script ')]
    TPL.write_text(head + ''.join(out), encoding='utf-8')
    return len(out)


