def limits():
    """{블록: 가장 작은 고정 버퍼} — script.build 에 넘겨 넘치는 블록만 같은 스크립트를 합치게 한다."""
    out = {}
    for b, size, _ in FIXED:
        out[b] = min(size, out.get(b, size))
    return out


def check(blocks):
    """넘치는 블록 [(블록, 크기, 버퍼, 읽는 곳)]"""
    return [(b, len(blocks[b]), size, where) for b, size, where in FIXED if len(blocks[b]) > size]


def patch_arm9(data):
    """ARM9 바이트를 고친다. 고친 자리 [(주소, 바이트 수)]."""
    import engine
    import relocate
    spans = []
    for addr, old, new, why in ARM9_PATCHES:
        a = None
        for before, after in ((12, 20), (0, 12), (0, 8)):   # 앞뒤에 판본마다 다른 bl 이 있으면 좁혀 찾는다
            try:
                a = relocate.code(addr, before, after)
                break
            except SystemExit:
                continue
        if a is None:
            sys.exit(f'{addr:#x}({why})를 찾지 못했습니다.')
        i = a - engine.ARM9_BASE
        old, new = bytes.fromhex(old), bytes.fromhex(new)
        if data[i:i + len(old)] != old:
            sys.exit(f'{a:#x}: 예상한 바이트가 아닙니다 ({why}).')
        data[i:i + len(new)] = new
        spans.append((a, len(new)))
    return spans


